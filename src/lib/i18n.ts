export const STRINGS: Record<Lang, Record<Key, string>> = { en, ne };

export function t(lang: Lang, key: Key, vars: Record<string, string> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? `{${k}}`);
}

